"""Generate the FastRobox KiCad project from one list of nets.

Single source of truth: NETS below. It mirrors docs/FastRobox_Pin_Connections.md (section 3).
Run:  python kicad/tools/generate_kicad.py   (from the repository root)

Writes:
  kicad/FastRobox.kicad_pro
  kicad/FastRobox.kicad_sch     (symbols embedded; connections are net labels on pin ends)
  kicad/FastRobox.kicad_pcb     (board outline only; use Update PCB from Schematic to place footprints)
  kicad/fastrobox.kicad_sym     (custom symbols, reusable from the library)
  kicad/sym-lib-table

Status: UNVERIFIED. Generated by script, not opened in KiCad from this environment.
"""
import os
import uuid

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.abspath(os.path.join(HERE, ".."))
PITCH = 2.54
BODY_X = 5.08          # half width of symbol body
PIN_LEN = 2.54
PIN_X = -(BODY_X + PIN_LEN)   # left-side pins, connection point at x = -7.62


def new_uuid():
    return str(uuid.uuid4())


# ---- custom symbols: each is a single column of pins, top pin first ----------
SYMBOLS = {
    "ESP32S3_FR": {
        "value": "ESP32-S3-WROOM CAM (N16R8)",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x11_P2.54mm_Vertical",
        "pins": ["3V3", "GND", "GPIO38", "GPIO21", "GPIO47", "GPIO41", "GPIO42",
                 "GPIO39", "GPIO40", "GPIO2", "GPIO1"],
    },
    "RC522_FR": {
        "value": "RFID-RC522 (HW-126)",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x08_P2.54mm_Vertical",
        "pins": ["3.3V", "RST", "GND", "IRQ", "MISO", "MOSI", "SCK", "SDA"],
    },
    "DHT11_FR": {
        "value": "DHT11 module",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x03_P2.54mm_Vertical",
        "pins": ["GND", "DATA", "VCC"],
    },
    "FLAME_FR": {
        "value": "IR flame sensor (3-pin)",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x03_P2.54mm_Vertical",
        "pins": ["DO", "GND", "VCC"],
    },
    "BUZZER_FR": {
        "value": "Active buzzer (2-pin)",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x02_P2.54mm_Vertical",
        "pins": ["+", "-"],
    },
    "TOUCH_FR": {
        "value": "Touch panic pad (bare wire end)",
        "footprint": "Connector_PinHeader_2.54mm:PinHeader_1x01_P2.54mm_Vertical",
        "pins": ["PAD"],
    },
}

# instance placement on the sheet (ESP32 on the left, modules on the right)
PLACE = {
    "U1": ("ESP32S3_FR", 100.0, 50.0),
    "U2": ("RC522_FR", 180.0, 40.0),
    "U3": ("DHT11_FR", 180.0, 102.0),
    "U4": ("FLAME_FR", 180.0, 132.0),
    "BZ1": ("BUZZER_FR", 180.0, 170.0),
    "TP1": ("TOUCH_FR", 180.0, 190.0),
}

# net name -> list of (reference, pin name). Every row of the pin table is one of these.
NETS = {
    "3V3": [("U1", "3V3"), ("U2", "3.3V"), ("U3", "VCC"), ("U4", "VCC")],
    "GND": [("U1", "GND"), ("U2", "GND"), ("U3", "GND"), ("U4", "GND"), ("BZ1", "-")],
    "GPIO38": [("U1", "GPIO38"), ("U2", "RST")],
    "GPIO21": [("U1", "GPIO21"), ("U2", "MISO")],
    "GPIO47": [("U1", "GPIO47"), ("U2", "MOSI")],
    "GPIO41": [("U1", "GPIO41"), ("U2", "SCK")],
    "GPIO42": [("U1", "GPIO42"), ("U2", "SDA")],
    "GPIO39": [("U1", "GPIO39"), ("U3", "DATA")],
    "GPIO40": [("U1", "GPIO40"), ("U4", "DO")],
    "GPIO2": [("U1", "GPIO2"), ("BZ1", "+")],
    "GPIO1": [("U1", "GPIO1"), ("TP1", "PAD")],
}
NO_CONNECT = [("U2", "IRQ")]   # RC522 IRQ is optional and not wired


def pin_point(ref, pin):
    """Connection point of a pin on the sheet (schematic y grows downward)."""
    sym, ix, iy = PLACE[ref]
    idx = SYMBOLS[sym]["pins"].index(pin)
    return ix + PIN_X, iy + idx * PITCH


def fmt(v):
    s = f"{v:.2f}".rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def lib_symbol_sexpr(name, spec, lib_prefix):
    pins = spec["pins"]
    n = len(pins)
    top = PITCH / 2
    bottom = -(n - 1) * PITCH - PITCH / 2
    lines = []
    lines.append(f'    (symbol "{lib_prefix}{name}" (pin_names (offset 1.016)) (in_bom yes) (on_board yes)')
    lines.append(f'      (property "Reference" "U" (at 0 {fmt(top + 1)} 0) (effects (font (size 1.27 1.27))))')
    lines.append(f'      (property "Value" "{spec["value"]}" (at 0 {fmt(bottom - 1)} 0) (effects (font (size 1.27 1.27))))')
    lines.append(f'      (property "Footprint" "{spec["footprint"]}" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))')
    lines.append(f'      (property "Datasheet" "" (at 0 0 0) (effects (font (size 1.27 1.27)) (hide yes)))')
    lines.append(f'      (symbol "{lib_prefix}{name}_0_1"')
    lines.append(f'        (rectangle (start {fmt(-BODY_X)} {fmt(top)}) (end {fmt(BODY_X)} {fmt(bottom)})')
    lines.append(f'          (stroke (width 0.254) (type default)) (fill (type background))))')
    lines.append(f'      (symbol "{lib_prefix}{name}_1_1"')
    for i, p in enumerate(pins):
        y = -i * PITCH
        lines.append(f'        (pin passive line (at {fmt(PIN_X)} {fmt(y)} 0) (length {fmt(PIN_LEN)})')
        lines.append(f'          (name "{p}" (effects (font (size 1.016 1.016))))')
        lines.append(f'          (number "{i + 1}" (effects (font (size 1.016 1.016)))))')
    lines.append("      )")
    lines.append("    )")
    return "\n".join(lines)


def write_symbol_library():
    parts = ['(kicad_symbol_lib (version 20231120) (generator "fastrobox_gen") (generator_version "1.0")']
    for name, spec in SYMBOLS.items():
        parts.append(lib_symbol_sexpr(name, spec, "").replace('"' + name, '"' + name, 1))
    parts.append(")")
    with open(os.path.join(OUT, "fastrobox.kicad_sym"), "w", encoding="utf-8") as f:
        f.write("\n".join(parts) + "\n")


def write_schematic():
    root = new_uuid()
    out = []
    out.append(f'(kicad_sch (version 20231120) (generator "fastrobox_gen") (generator_version "1.0") (uuid "{root}")')
    out.append('  (paper "A3")')
    out.append('  (title_block (title "FastRobox 1.0 - Smart Classroom wiring") (rev "A") (company "Team FastRobox") (comment 1 "UNVERIFIED: not tested on hardware"))')
    out.append("  (lib_symbols")
    for name, spec in SYMBOLS.items():
        out.append(lib_symbol_sexpr(name, spec, "fastrobox:"))
    out.append("  )")
    for ref, (sym, x, y) in PLACE.items():
        spec = SYMBOLS[sym]
        out.append(f'  (symbol (lib_id "fastrobox:{sym}") (at {fmt(x)} {fmt(y)} 0) (unit 1) (in_bom yes) (on_board yes) (dnp no)')
        out.append(f'    (uuid "{new_uuid()}")')
        out.append(f'    (property "Reference" "{ref}" (at {fmt(x)} {fmt(y - 4)} 0) (effects (font (size 1.27 1.27))))')
        out.append(f'    (property "Value" "{spec["value"]}" (at {fmt(x)} {fmt(y + len(spec["pins"]) * PITCH + 3)} 0) (effects (font (size 1.27 1.27))))')
        out.append(f'    (property "Footprint" "{spec["footprint"]}" (at {fmt(x)} {fmt(y)} 0) (effects (font (size 1.27 1.27)) (hide yes)))')
        out.append(f'    (property "Datasheet" "" (at {fmt(x)} {fmt(y)} 0) (effects (font (size 1.27 1.27)) (hide yes)))')
        for i in range(len(spec["pins"])):
            out.append(f'    (pin "{i + 1}" (uuid "{new_uuid()}"))')
        out.append(f'    (instances (project "FastRobox" (path "/{root}" (reference "{ref}") (unit 1))))')
        out.append("  )")
    # net labels sit exactly on pin connection points, so each name joins its pins
    for net, pins in NETS.items():
        for ref, pin in pins:
            px, py = pin_point(ref, pin)
            out.append(f'  (label "{net}" (at {fmt(px)} {fmt(py)} 0) (fields_autoplaced yes)')
            out.append('    (effects (font (size 1.27 1.27)) (justify left bottom)))')
    for ref, pin in NO_CONNECT:
        px, py = pin_point(ref, pin)
        out.append(f'  (no_connect (at {fmt(px)} {fmt(py)}) (uuid "{new_uuid()}"))')
    out.append('  (text "FastRobox 1.0 wiring. Pin assignments follow docs/FastRobox_Pin_Connections.md. UNVERIFIED until tested on the board. Camera not drawn (internal to the CAM board)." (at 20 20 0) (effects (font (size 2 2)) (justify left)))')
    out.append('  (sheet_instances (path "/" (page "1")))')
    out.append(")")
    with open(os.path.join(OUT, "FastRobox.kicad_sch"), "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")


def write_project():
    pro = {
        "meta": {"filename": "FastRobox.kicad_pro", "version": 1},
        "board": {"design_settings": {}, "layer_presets": [], "viewports": []},
        "boards": [],
        "libraries": {"pinned_symbol_libs": [], "pinned_footprint_libs": []},
        "schematic": {"drawing": {}, "legacy_lib_dir": "", "legacy_lib_list": []},
        "sheets": [],
        "text_variables": {},
    }
    import json
    with open(os.path.join(OUT, "FastRobox.kicad_pro"), "w", encoding="utf-8") as f:
        json.dump(pro, f, indent=2)
        f.write("\n")


def write_pcb():
    # Board outline 100 x 70 mm. Footprints are added by Update PCB from Schematic in KiCad.
    w, h = 100.0, 70.0
    lines = [
        '(kicad_pcb (version 20240108) (generator "fastrobox_gen") (generator_version "1.0")',
        '  (general (thickness 1.6))',
        '  (paper "A4")',
        '  (layers (0 "F.Cu" signal) (31 "B.Cu" signal) (44 "Edge.Cuts" user) (37 "F.SilkS" user "F.Silkscreen"))',
        '  (setup (pad_to_mask_clearance 0))',
        '  (net 0 "")',
    ]
    corners = [(0, 0), (w, 0), (w, h), (0, h)]
    for i in range(4):
        (x1, y1), (x2, y2) = corners[i], corners[(i + 1) % 4]
        lines.append(f'  (gr_line (start {fmt(x1)} {fmt(y1)}) (end {fmt(x2)} {fmt(y2)}) (stroke (width 0.1) (type default)) (layer "Edge.Cuts") (uuid "{new_uuid()}"))')
    lines.append(")")
    with open(os.path.join(OUT, "FastRobox.kicad_pcb"), "w", encoding="utf-8") as f:
        f.write("\n".join(lines) + "\n")


def write_lib_table():
    text = ('(sym_lib_table\n'
            '  (version 7)\n'
            '  (lib (name "fastrobox") (type "KiCad") (uri "${KIPRJMOD}/fastrobox.kicad_sym") (options "") (descr "FastRobox custom parts"))\n'
            ')\n')
    with open(os.path.join(OUT, "sym-lib-table"), "w", encoding="utf-8") as f:
        f.write(text)


def check_labels_on_pins():
    # every pin of every instance must appear in exactly one net, except the optional RC522 IRQ
    used = {}
    for net, pins in NETS.items():
        for ref, pin in pins:
            used[(ref, pin)] = net
    for ref, (sym, _, _) in PLACE.items():
        for pin in SYMBOLS[sym]["pins"]:
            if (ref, pin) not in used and (ref, pin) not in NO_CONNECT:
                print(f"note: {ref} {pin} is not connected (ok for the touch pad / unused ESP pins)")
    dup = [k for k in used if sum(1 for n in NETS.values() for r, p in n if (r, p) == k) > 1]
    assert not dup, dup


if __name__ == "__main__":
    check_labels_on_pins()
    write_symbol_library()
    write_schematic()
    write_project()
    write_pcb()
    write_lib_table()
    print("KiCad files written to", OUT)
