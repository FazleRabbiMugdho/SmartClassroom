const dictionaries: Record<Locale, Dict> = { en, bn };

export function resolveLocale(value: string | undefined | null): Locale {
  return value === "bn" ? "bn" : "en";
}

export function t(locale: Locale, key: string): string {
  return dictionaries[locale][key] ?? dictionaries.en[key] ?? key;
}

/** All keys under a prefix, with the prefix stripped (passed to client components as props). */
export function labelsFor(locale: Locale, prefix: string): Record<string, string> {
  const out: Record<string, string> = {};
  for (const key of Object.keys(dictionaries.en)) {
    if (key.startsWith(prefix + ".")) out[key.slice(prefix.length + 1)] = t(locale, key);
  }
  return out;
}
