"""Turn firmware/data/*.html into a C++ header, so the web pages live inside the firmware.

Run from the firmware folder after editing a page:
    python tools/embed_pages.py

Writes src/levels/level02/web_pages.h. The pages are then served from memory, so the board
does not need a separate LittleFS upload (that upload failed to mount on the board).
"""
import os

HERE = os.path.dirname(os.path.abspath(__file__))
FW = os.path.abspath(os.path.join(HERE, ".."))
PAGES = [("INDEX_HTML", "index.html"), ("SETUP_HTML", "setup.html")]
OUT = os.path.join(FW, "src", "levels", "level02", "web_pages.h")

lines = [
    "// Generated by tools/embed_pages.py from firmware/data/*.html. Do not edit by hand.",
    "#pragma once",
    "",
]
for var, name in PAGES:
    text = open(os.path.join(FW, "data", name), encoding="utf-8").read()
    assert ')HTML"' not in text, f"{name} contains the raw-string end marker"
    lines.append(f"static const char {var}[] PROGMEM = R\"HTML(")
    lines.append(text.rstrip("\n"))
    lines.append(')HTML";')
    lines.append("")

with open(OUT, "w", encoding="utf-8", newline="\n") as f:
    f.write("\n".join(lines))
print("wrote", OUT)
